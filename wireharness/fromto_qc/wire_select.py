# -*- coding: utf-8 -*-
"""古川基準(FS-7C-001/FS-1A-003) 電線サイズ選定。太物判定の確定根拠。

主回路電線サイズは「定格出力(kW) × 負荷率(①*1.0 / ②*0.6 / ③*0.35)」で選定する
(負荷率①＝24時間操業=稼働時間、②③＝低稼働。顧客仕様/稼働時間で決まる)。
または 定格電流(AT) → 電線サイズ(許容電流表)。
ハーネスに含めるのは 5.5sq 以下。8sq 以上は『太物』でハーネスと別扱い(端子台はEのみ)。

本モジュールは選定表を保持し、kW(+電圧+負荷率) または AT から電線サイズを返す。
太物しきい値 FUTO_SQ=5.5 (これ超=太物)。
"""
FUTO_SQ = 5.5

# 制御盤 主回路電線 kW → [①*1.0, ②*0.6, ③*0.35] (FS-7C-001-03/04)
# None は表に無し(小容量で下位相当)。
_KW_200V = {
    0.2: [2, 2, 2], 0.4: [2, 2, 2], 0.75: [2, 2, 2], 1.5: [2, 2, 2], 2.2: [2, 2, 2],
    3.7: [3.5, 2, 2], 5.5: [5.5, 2, 2], 7.5: [8, 5.5, 2], 11: [14, 5.5, 3.5],
    15: [22, 8, 5.5], 18.5: [38, 14, 5.5], 22: [38, 14, 8], 30: [60, 22, 14],
    37: [60, 38, 14], 45: [100, 38, 22], 55: [150, 60, 38], 75: [150, 100, 60],
}
_KW_400V = {
    5.5: [2, 2, 2], 7.5: [3.5, 2, 2], 11: [5.5, 2, 2], 15: [8, 3.5, 2],
    18.5: [14, 5.5, 2], 22: [14, 5.5, 3.5], 30: [22, 8, 5.5], 37: [38, 14, 5.5],
    45: [38, 14, 8], 55: [38, 22, 8], 75: [60, 38, 14], 90: [100, 38, 14],
    110: [100, 60, 38], 132: [150, 100, 38],
}
# 制御盤 動力回路 定格電流(AT) → 電線サイズ (許容電流表, 周囲温度40℃)
_AT = [
    (15, 2), (20, 3.5), (30, 5.5), (40, 8), (50, 14), (60, 22), (75, 22),
    (100, 38), (125, 38), (150, 60), (175, 60), (200, 100), (225, 100),
    (250, 150), (300, 150), (350, 200), (400, 250), (500, 325), (600, 325),
]
_FACTOR_IDX = {'1.0': 0, '0.6': 1, '0.35': 2, 1: 0, 2: 1, 3: 2}


def by_kw(kw, voltage=200, factor='0.35'):
    """定格出力(kW) → 電線サイズ(sq)。負荷率 factor=1.0/0.6/0.35。表に無ければ None。"""
    try:
        kw = float(kw)
    except Exception:
        return None
    tbl = _KW_400V if int(voltage) >= 400 else _KW_200V
    idx = _FACTOR_IDX.get(factor, 2)
    # kw 以上で最小の表キー(直近上位)
    keys = sorted(tbl)
    pick = None
    for k in keys:
        if kw <= k + 1e-9:
            pick = k
            break
    if pick is None:
        pick = keys[-1]
    return tbl[pick][idx]


def by_at(at):
    """定格電流(AT) → 電線サイズ(sq)。"""
    try:
        at = float(at)
    except Exception:
        return None
    for a, sq in _AT:
        if at <= a + 1e-9:
            return sq
    return _AT[-1][1]


def is_futo(sq):
    """電線サイズ(sq) → 太物か(5.5sq超)。"""
    try:
        return float(sq) > FUTO_SQ
    except Exception:
        return False
